import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractVideoId } from './dedupe-videos.mjs';

const OEMBED_ENDPOINT = 'https://www.tiktok.com/oembed';
const USER_AGENT = 'Mozilla/5.0 (compatible; covidtok-embed-check/1.0)';

const OK_TTL_MS = 30 * 24 * 60 * 60 * 1000;
const BLOCKED_TTL_MS = 3 * 24 * 60 * 60 * 1000;

const CONCURRENCY = 4;
const REQUEST_GAP_MS = 150;
const REQUEST_TIMEOUT_MS = 8000;

// A cold catalog takes minutes to probe, so work is time-boxed and flushed as it goes.
// Whatever is left is picked up by the next run.
const DEFAULT_BUDGET_MS = 45000;
const FLUSH_EVERY = 100;
const OFFLINE_STREAK = 25;

// Statuses that mean the video is genuinely unavailable rather than temporarily unreachable.
const FATAL_STATUSES = new Set([400, 403, 404, 410]);

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CATALOG_PATH = join(REPO_ROOT, 'data', 'videos.txt');
const CACHE_PATH = join(REPO_ROOT, 'data', 'embed-cache.json');
const GENERATED_PATH = join(REPO_ROOT, 'src', 'generated', 'embeddable.ts');

function sleep(ms) {
  return new Promise((done) => setTimeout(done, ms));
}

function readCatalogEntries(text) {
  const entries = new Map();
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const id = extractVideoId(line);
    if (!id || entries.has(id)) continue;
    entries.set(id, {
      id,
      url: line.includes('tiktok.com') ? line : `https://www.tiktok.com/@_/video/${id}`,
    });
  }
  return [...entries.values()];
}

async function readCache() {
  try {
    const raw = await readFile(CACHE_PATH, 'utf8');
    const parsed = JSON.parse(raw);
    if (parsed && typeof parsed === 'object' && parsed.entries && typeof parsed.entries === 'object') {
      return parsed.entries;
    }
  } catch {
    // A missing or corrupt cache just means a full re-check.
  }
  return {};
}

function isFresh(record, now) {
  if (!record || typeof record.checkedAt !== 'number') return false;
  const ttl = record.ok ? OK_TTL_MS : BLOCKED_TTL_MS;
  return now - record.checkedAt < ttl;
}

/**
 * Resolves to true (embeddable), false (definitively gone or embed-disabled), or
 * null when the answer is unknown. Unknown never blocks a video.
 */
async function probeEmbeddable(url) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);
  try {
    const response = await fetch(`${OEMBED_ENDPOINT}?url=${encodeURIComponent(url)}`, {
      signal: controller.signal,
      headers: { 'user-agent': USER_AGENT, accept: 'application/json' },
    });

    if (FATAL_STATUSES.has(response.status)) return false;
    if (!response.ok) return null;

    const payload = await response.json();
    if (!payload || typeof payload !== 'object') return null;
    if (typeof payload.status_code === 'number' && payload.status_code !== 0) return false;
    if (typeof payload.html === 'string' || typeof payload.thumbnail_url === 'string') return true;
    return null;
  } catch {
    return null;
  } finally {
    clearTimeout(timer);
  }
}

async function writeIfChanged(path, next) {
  try {
    const current = await readFile(path, 'utf8');
    if (current === next) return false;
  } catch {
    // File does not exist yet.
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, next);
  return true;
}

function renderGeneratedModule(blockedIds, checkedAt) {
  const list = blockedIds.length === 0
    ? '[]'
    : `[\n${blockedIds.map((id) => `  '${id}',`).join('\n')}\n]`;
  return [
    '// Generated by scripts/check-embeddable.mjs. Do not edit by hand.',
    `export const BLOCKED_VIDEO_IDS: readonly string[] = ${list};`,
    `export const CHECKED_AT = ${checkedAt};`,
    '',
  ].join('\n');
}

/** Writes a placeholder module so the app compiles before the first probe finishes. */
export async function ensureGeneratedModule() {
  try {
    await readFile(GENERATED_PATH, 'utf8');
  } catch {
    await mkdir(dirname(GENERATED_PATH), { recursive: true });
    await writeFile(GENERATED_PATH, renderGeneratedModule([], 0));
  }
}

export async function checkEmbeddable({ silent = false, budgetMs = DEFAULT_BUDGET_MS } = {}) {
  const catalogText = await readFile(CATALOG_PATH, 'utf8');
  const entries = readCatalogEntries(catalogText);
  const cache = await readCache();
  const now = Date.now();

  const catalogIds = new Set(entries.map((entry) => entry.id));
  for (const id of Object.keys(cache)) {
    if (!catalogIds.has(id)) delete cache[id];
  }

  const writeCache = () => writeIfChanged(
    CACHE_PATH,
    `${JSON.stringify({ version: 1, entries: cache }, null, 2)}\n`,
  );

  const queue = entries.filter((entry) => !isFresh(cache[entry.id], now));
  const deadline = Date.now() + budgetMs;
  let checked = 0;
  let unreachable = 0;
  let offlineStreak = 0;
  let sinceFlush = 0;

  const workers = Array.from({ length: Math.min(CONCURRENCY, queue.length) }, async () => {
    while (queue.length > 0) {
      if (Date.now() > deadline || offlineStreak >= OFFLINE_STREAK) break;
      const entry = queue.shift();
      if (!entry) break;

      const ok = await probeEmbeddable(entry.url);
      checked += 1;
      if (ok === null) {
        unreachable += 1;
        offlineStreak += 1;
      } else {
        offlineStreak = 0;
        cache[entry.id] = { ok, checkedAt: Date.now() };
      }

      sinceFlush += 1;
      if (sinceFlush >= FLUSH_EVERY) {
        sinceFlush = 0;
        await writeCache();
      }
      await sleep(REQUEST_GAP_MS);
    }
  });
  await Promise.all(workers);

  const blockedIds = entries
    .filter((entry) => cache[entry.id]?.ok === false)
    .map((entry) => entry.id);

  await writeCache();
  const wrote = await writeIfChanged(GENERATED_PATH, renderGeneratedModule(blockedIds, now));

  if (!silent) {
    const parts = [`Embed gate: ${entries.length} videos, ${blockedIds.length} blocked`];
    if (checked > 0) parts.push(`${checked} probed`);
    if (unreachable > 0) parts.push(`${unreachable} unreachable (kept)`);
    if (queue.length > 0) parts.push(`${queue.length} deferred to next run`);
    console.log(`${parts.join(', ')}.`);
  }

  return { total: entries.length, blocked: blockedIds.length, checked, unreachable, pending: queue.length, wrote };
}

const isDirectRun = String(process.argv[1] ?? '').replaceAll('\\', '/').endsWith('scripts/check-embeddable.mjs');

if (isDirectRun) {
  await ensureGeneratedModule();
  await checkEmbeddable({ budgetMs: Number.POSITIVE_INFINITY });
}
